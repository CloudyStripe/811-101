/**
 * Generates docs/CONTENT_REVIEW.md: every factual claim, for locator sign-off.
 * `--check` fails instead of writing when the file is stale.
 *
 * Sign-offs live in content/review/signoffs.json as
 *   { "<claim id>": { "hash": "<hash shown in the review>", "by": "<initials>", "date": "YYYY-MM-DD" } }
 * A sign-off only counts while the claim's text still matches its hash.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { FREQUENCIES, frequencyLabel } from '../config/equipment.ts';
import { CONTENT_MODULES } from '../content/index.ts';
import { SOURCES, type SourceId } from '../content/sources.ts';
import { APWA, DIORAMA_APWA, LAB_APWA, MARKS_APWA } from '../src/design/apwa.ts';
import { collectClaims, type Claim } from '../src/content-kit/claims.ts';
import { plainText } from '../src/content-kit/terms.ts';
import { ALL_CONSTANTS, type Constant, type PerFrequency } from '../src/signal/constants.ts';

const OUT = 'docs/CONTENT_REVIEW.md';

interface SignOff {
  hash: string;
  by: string;
  date: string;
}

const signoffs = JSON.parse(await readFile('content/review/signoffs.json', 'utf8')) as Record<
  string,
  SignOff
>;

const hash = (text: string) => createHash('sha256').update(text).digest('hex').slice(0, 10);
const cell = (text: string) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

function status(id: string, text: string): string {
  const s = signoffs[id];
  if (!s) return 'Not reviewed';
  return s.hash === hash(text) ? `Signed off by ${s.by}, ${s.date}` : 'Changed since sign-off';
}

/** Where a claim comes from, by the short names the sources list gives them. */
const SOURCE_NAMES: Record<SourceId, string> = {
  'apwa-card': 'APWA card',
  'cga-best-practices-b': 'CGA Best Practices',
  'bls-surveyors': 'BLS',
  'fcc-conduit': 'FCC',
  'mw-conduit': 'Merriam-Webster (conduit)',
  'usgs-glossary': 'USGS glossary',
  'mw-slurry': 'Merriam-Webster (slurry)',
  'usgs-coal-slurry': 'USGS coal slurry study',
  scene: 'The scene',
  game: 'The game',
};

const sourceCell = (c: Claim) =>
  c.source?.length ? c.source.map((s) => SOURCE_NAMES[s]).join(', ') : '—';

/** Claims are listed and hashed as read, without term markup: only a change of wording needs re-review. */
function claimRows(claims: readonly Claim[]): string[] {
  return claims.map((c) => {
    const text = plainText(c.text);
    return `| \`${c.id}\` | ${cell(text)}${c.note ? ` _(${cell(c.note)})_` : ''} | ${sourceCell(c)} | ${c.stateSpecific ? 'Yes' : 'No'} | \`${hash(text)}\` | ${status(c.id, text)} |`;
  });
}

/** The sources claims cite, each with its link. */
function sourceList(): string[] {
  return (Object.keys(SOURCES) as SourceId[]).map((id) => {
    const s: { title: string; publisher: string; url?: string } = SOURCES[id];
    return s.url
      ? `- **${SOURCE_NAMES[id]}:** [${s.title}](${s.url}), ${s.publisher}.`
      : `- **${SOURCE_NAMES[id]}:** ${s.title}.`;
  });
}

const valueText = (c: Constant<number | PerFrequency>) =>
  typeof c.value === 'number'
    ? `${c.value} ${c.unit}`
    : `${FREQUENCIES.map((f) => `${frequencyLabel(f)}: ${String((c.value as PerFrequency)[f])}`).join(', ')} (${c.unit})`;

const modelClaims = ALL_CONSTANTS.map((c) => ({
  id: `model.${c.name
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, '-')
    .replaceAll(/^-|-$/g, '')}`,
  text: `${c.name}: ${valueText(c)}. ${c.why}`,
}));

/** Every APWA color a lesson shows, once each. */
const usedApwa = [...new Set([...LAB_APWA, ...DIORAMA_APWA, ...MARKS_APWA])];

const colorClaims = usedApwa.map((code) => ({
  id: `apwa.${code}`,
  text: `${APWA[code].name} means ${APWA[code].meaning.toLowerCase()}; shown on screen as ${APWA[code].fill}.`,
}));

function render(): string {
  const parts = [
    '<!-- Generated by `npm run content:review`. Do not edit by hand. -->',
    '',
    '# Content review',
    '',
    'Every factual claim in the lessons, for locator sign-off.',
    '',
    "- **How to sign off:** add the claim to `content/review/signoffs.json` with the hash shown, your initials and the date. Or send the IDs and we'll add them.",
    '- **Edited claims:** editing a claim changes its hash and puts it back in review.',
    '',
    '**State-specific claims:** none so far. The lessons teach no state rules.',
    '',
    '**Sources:** the Source column says where a claim comes from, from these:',
    '',
    ...sourceList(),
  ];
  for (const mod of CONTENT_MODULES) {
    parts.push(
      '',
      `## ${mod.name}`,
      '',
      '| ID | Claim | Source | State-specific | Hash | Status |',
      '|---|---|---|---|---|---|',
      ...claimRows(collectClaims(mod.content)),
    );
  }
  parts.push(
    '',
    '## Signal model calibrations',
    '',
    'Teaching values from `src/signal/constants.ts`. `docs/SIGNAL_MODEL.md` explains how they combine and lists the eight resulting states.',
    '',
    '| ID | Calibration | Hash | Status |',
    '|---|---|---|---|',
    ...modelClaims.map(
      (c) => `| \`${c.id}\` | ${cell(c.text)} | \`${hash(c.text)}\` | ${status(c.id, c.text)} |`,
    ),
    '',
    '## Screen colors',
    '',
    'On-screen approximations of the APWA colors the lessons use.',
    '',
    '| ID | Claim | Hash | Status |',
    '|---|---|---|---|',
    ...colorClaims.map(
      (c) => `| \`${c.id}\` | ${cell(c.text)} | \`${hash(c.text)}\` | ${status(c.id, c.text)} |`,
    ),
    '',
  );
  return parts.join('\n');
}

const content = render();
if (process.argv.includes('--check')) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== content) {
    console.error(`${OUT} is out of date. Run \`npm run content:review\`.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  await writeFile(OUT, content);
  console.log(`Wrote ${OUT}.`);
}
